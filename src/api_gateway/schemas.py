def to_domain_transaction(req: TransactionIngestRequest) -> Transaction:
    """Convert an OpenAPI TransactionIngestRequest into a domain Transaction model."""
    details = req.transaction_details
    tx_id = details.transaction_id or f"tx_{uuid4().hex[:12]}"

    if details.transaction_type == "ACH":
        payment_method = PaymentMethod(
            payment_type="bank_transfer",
            card_last_four=details.ach_details.account_last_four if details.ach_details else None,
            is_card_present=False,
        )
    else:
        card = details.card_details
        payment_type: Literal["credit_card", "debit_card"] = (
            "debit_card" if card and card.card_type == "DEBIT" else "credit_card"
        )
        payment_method = PaymentMethod(
            payment_type=payment_type,
            card_last_four=card.card_last_four if card else None,
            is_card_present=card.is_card_present if card else False,
        )

    if details.merchant is not None:
        merchant = MerchantInfo(
            merchant_id=details.merchant.merchant_id,
            name=details.merchant.name,
            mcc=details.merchant.mcc,
            country=details.merchant.country,
        )
    else:
        default_mcc = "6012" if details.transaction_type == "ACH" else "5999"
        default_name = (
            details.ach_details.bank_name or "ACH Counterparty"
            if details.transaction_type == "ACH" and details.ach_details
            else "Standard Merchant"
        )
        merchant = MerchantInfo(
            merchant_id="merch_default_01",
            name=default_name,
            mcc=default_mcc,
            country=req.location.country,
        )

    return Transaction(
        transaction_id=tx_id,
        account_id=req.username,
        amount=details.amount,
        currency=details.currency,
        timestamp=req.datetime,
        location=GeoLocation(
            latitude=req.location.latitude,
            longitude=req.location.longitude,
            city=req.location.city,
            country=req.location.country,
        ),
        payment_method=payment_method,
        merchant=merchant,
        device_id=req.device_id,
        ip_address=req.ip,
    )
