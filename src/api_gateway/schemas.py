"""OpenAPI v3 request, response, and WebSocket event schemas for the FastAPI Gateway."""

import datetime as dt
from datetime import UTC
from typing import Any, Literal
from uuid import uuid4

from pydantic import BaseModel, Field, model_validator

from fraud_scorer.models.transaction import (
    GeoLocation,
    MerchantInfo,
    PaymentMethod,
    RiskFactor,
    Transaction,
)

TransactionStatus = Literal["APPROVE", "REVIEW", "DECLINE", "ACCEPTED", "REJECTED"]


class GeoLocationSchema(BaseModel):
    """Geographic coordinates and location metadata for API ingestion."""

    latitude: float = Field(..., ge=-90.0, le=90.0, description="Latitude in decimal degrees.")
    longitude: float = Field(..., ge=-180.0, le=180.0, description="Longitude in decimal degrees.")
    city: str | None = Field(default=None, description="City name if available.")
    state: str | None = Field(default=None, description="State, province, or region code.")
    country: str = Field(
        default="US",
        min_length=2,
        max_length=3,
        description="ISO 3166-1 alpha-2 or alpha-3 country code.",
    )
    postal_code: str | None = Field(default=None, description="Postal or ZIP code.")


class MerchantInfoSchema(BaseModel):
    """Merchant identity and categorization."""

    merchant_id: str = Field(..., description="Unique merchant identifier.")
    name: str = Field(..., description="Merchant commercial name.")
    mcc: str = Field(
        ...,
        pattern=r"^[0-9]{4}$",
        description="4-digit Merchant Category Code (MCC).",
    )
    country: str = Field(default="US", description="Merchant country code.")


class ACHTransactionDetails(BaseModel):
    """Bank transfer details for ACH transactions."""

    routing_number: str = Field(
        ...,
        pattern=r"^[0-9]{9}$",
        description="9-digit ABA bank routing transit number.",
    )
    account_last_four: str = Field(
        ...,
        pattern=r"^[0-9]{4}$",
        description="Last 4 digits of the bank account number.",
    )
    account_type: Literal["CHECKING", "SAVINGS", "BUSINESS"] = Field(
        ...,
        description="Type of bank account used for the ACH transfer.",
    )
    sec_code: Literal["WEB", "PPD", "CCD", "TEL"] = Field(
        default="WEB",
        description="NACHA Standard Entry Class (SEC) code.",
    )
    direction: Literal["DEBIT", "CREDIT"] = Field(
        ...,
        description="Transfer direction (DEBIT pull or CREDIT push).",
    )
    bank_name: str | None = Field(
        default=None,
        description="Name of the originating or receiving financial institution.",
    )


class CardTransactionDetails(BaseModel):
    """Payment card details for credit/debit card transactions."""

    card_type: Literal["CREDIT", "DEBIT", "PREPAID"] = Field(
        ...,
        description="Funding category of the payment card.",
    )
    card_network: Literal["VISA", "MASTERCARD", "AMEX", "DISCOVER", "OTHER"] | None = Field(
        default="VISA",
        description="Card brand network.",
    )
    card_last_four: str = Field(
        ...,
        pattern=r"^[0-9]{4}$",
        description="Last 4 digits of the Primary Account Number (PAN).",
    )
    bin_prefix: str | None = Field(
        default=None,
        pattern=r"^[0-9]{6,8}$",
        description="Optional 6-to-8 digit Bank Identification Number (BIN).",
    )
    is_card_present: bool = Field(
        default=False,
        description="Whether the physical card was present at a POS terminal.",
    )
    expiration_month: int | None = Field(
        default=None,
        ge=1,
        le=12,
        description="Card expiration month (1-12).",
    )
    expiration_year: int | None = Field(
        default=None,
        ge=2024,
        le=2050,
        description="4-digit card expiration year.",
    )
    cvv_verified: bool | None = Field(
        default=None,
        description="Whether CVV/CVC verification succeeded.",
    )
    avs_result: str | None = Field(
        default=None,
        description="Address Verification System (AVS) response code.",
    )


class TransactionDetails(BaseModel):
    """Polymorphic transaction details supporting ACH or CARD rails."""

    transaction_id: str | None = Field(
        default=None,
        description="Optional client-supplied transaction ID; generated by server if omitted.",
    )
    transaction_type: Literal["ACH", "CARD"] = Field(
        ...,
        description="Payment rail type (ACH or CARD).",
    )
    amount: float = Field(
        ...,
        gt=0.0,
        description="Transaction amount in the specified currency.",
    )
    currency: str = Field(
        default="USD",
        min_length=3,
        max_length=3,
        description="Three-letter ISO 4217 currency code.",
    )
    merchant: MerchantInfoSchema | None = Field(
        default=None,
        description="Merchant receiving payment.",
    )
    ach_details: ACHTransactionDetails | None = Field(
        default=None,
        description="Required when transaction_type is ACH.",
    )
    card_details: CardTransactionDetails | None = Field(
        default=None,
        description="Required when transaction_type is CARD.",
    )

    @model_validator(mode="after")
    def validate_payment_rail_details(self) -> "TransactionDetails":
        """Ensure ach_details or card_details matches transaction_type."""
        if self.transaction_type == "ACH" and self.ach_details is None:
            raise ValueError("ach_details is required when transaction_type is 'ACH'")
        if self.transaction_type == "CARD" and self.card_details is None:
            raise ValueError("card_details is required when transaction_type is 'CARD'")
        return self


class TransactionIngestRequest(BaseModel):
    """Ingress payload for POST /api/v1/transactions/score."""

    username: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Unique username or customer account identifier.",
    )
    datetime: dt.datetime = Field(
        ...,
        description="ISO-8601 timestamp when the transaction was initiated.",
    )
    ip: str = Field(
        ...,
        description="IPv4 or IPv6 address of the user originating the transaction.",
    )
    device_id: str | None = Field(
        default=None,
        description="Optional device fingerprint or session identifier.",
    )
    location: GeoLocationSchema = Field(
        ...,
        description="Location where transaction originated.",
    )
    transaction_details: TransactionDetails = Field(
        ...,
        description="ACH or Card transaction details.",
    )


class TransactionScoreResponse(BaseModel):
    """Response payload for POST /api/v1/transactions/score."""

    transaction_id: str = Field(
        ...,
        description="Unique identifier assigned to the evaluated transaction.",
    )
    score: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Composite fraud risk score normalized between 0.0 and 100.0.",
    )
    status: TransactionStatus = Field(
        ...,
        description="Current fraud status / disposition of the transaction.",
    )
    evaluated_at: dt.datetime = Field(
        default_factory=lambda: dt.datetime.now(UTC),
        description="Timestamp when the fraud score was generated.",
    )


